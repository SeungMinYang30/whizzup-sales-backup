import { readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { strToU8, zipSync } from "fflate";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "lib", "generated-recovery-source.ts");

const includedRoots = [
  ".openai",
  "app",
  "db",
  "drizzle",
  "examples",
  "lib",
  "public",
  "scripts",
  "tests",
  "worker",
];

const includedFiles = [
  ".env.example",
  ".gitignore",
  "drizzle.config.ts",
  "eslint.config.mjs",
  "next.config.ts",
  "package-lock.json",
  "package.json",
  "postcss.config.mjs",
  "README.md",
  "tsconfig.json",
  "vite.config.ts",
];

const excludedNames = new Set([
  ".DS_Store",
  "generated-recovery-source.ts",
]);

async function collect(directory, archive, prefix = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name, "en"));
  for (const entry of entries) {
    if (excludedNames.has(entry.name)) continue;
    const absolute = path.join(directory, entry.name);
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      await collect(absolute, archive, relative);
    } else if (entry.isFile()) {
      archive[relative.replaceAll("\\", "/")] = new Uint8Array(
        await readFile(absolute),
      );
    }
  }
}

const archive = {};
for (const directory of includedRoots) {
  await collect(path.join(root, directory), archive, directory);
}
for (const filename of includedFiles) {
  archive[filename] = new Uint8Array(await readFile(path.join(root, filename)));
}

archive["RECOVERY_SOURCE_GUIDE.txt"] = strToU8(
  [
    "WHIZZUP TM·미팅 영업관리 소스 원본",
    "",
    "이 압축은 다른 호스팅 또는 새 Codex 작업에서 사이트를 복구하기 위한 원본입니다.",
    "node_modules, 빌드 결과, 로그인 세션, OAuth 토큰, API 키와 기타 비밀값은 포함하지 않습니다.",
    "",
    "복구 순서",
    "1. 이 ZIP의 압축을 풉니다.",
    "2. 비상복구 패키지에 함께 들어 있는 WHIZZUP_full_backup_*.json을 보관합니다.",
    "3. 새 Codex 작업에 압축을 푼 폴더와 DB 백업 파일을 연결합니다.",
    "4. .env.example을 기준으로 새 호스팅의 인증 및 환경값을 설정합니다.",
    "5. 다른 호스팅에서는 ChatGPT 로그인과 D1 데이터베이스 연결부를 해당 환경에 맞게 조정합니다.",
    "",
    "기본 실행",
    "npm install",
    "npm run build",
    "",
  ].join("\r\n"),
);

const zipped = zipSync(archive, {
  level: 9,
  mtime: new Date("2020-01-01T00:00:00.000Z"),
});
const encoded = Buffer.from(zipped).toString("base64");
const sourceSha256 = createHash("sha256").update(zipped).digest("hex");
const sourceFileCount = Object.keys(archive).length;

await writeFile(
  outputPath,
  [
    "// Generated by scripts/generate-recovery-source.mjs.",
    "// Do not edit this file by hand.",
    `export const RECOVERY_SOURCE_FILE_COUNT = ${sourceFileCount};`,
    `export const RECOVERY_SOURCE_SHA256 = ${JSON.stringify(sourceSha256)};`,
    `export const RECOVERY_SOURCE_ZIP_BASE64 = ${JSON.stringify(encoded)};`,
    "",
  ].join("\n"),
  "utf8",
);

console.log(
  `Generated recovery source asset: ${sourceFileCount} files, ${zipped.length} bytes`,
);
